/**
 * Corpus statistics over parsed ASTs — the numeric half of the stage 1.3
 * artifacts. Everything here is deterministic: histograms are emitted with
 * sorted keys so regenerated output diffs clean.
 */

import type { ProgramNode, ZilNode } from "./ast.js";

export interface FileStats {
  file: string;
  bytes: number;
  lines: number;
  /** Total AST nodes in the file (all depths). */
  nodes: number;
  /** Top-level node counts by AST type (Form, String, Comment, Atom, MacroEval). */
  topLevelTypes: Record<string, number>;
  /** Top-level form counts by head atom (ROOM, OBJECT, ROUTINE, GLOBAL, …). */
  topLevelHeads: Record<string, number>;
  /** Form counts by head atom at any depth (includes TELL, COND, TABLE, …). */
  deepHeads: Record<string, number>;
  /** Historical page-break atoms at top level (`\`+FF, `^L`, `/^L`). */
  pageBreaks: number;
}

export interface CorpusStats {
  generatedBy: string;
  files: FileStats[];
  totals: {
    bytes: number;
    lines: number;
    nodes: number;
    topLevelHeads: Record<string, number>;
    deepHeads: Record<string, number>;
  };
}

function sortRecord(rec: Record<string, number>): Record<string, number> {
  return Object.fromEntries(Object.entries(rec).sort(([a], [b]) => (a < b ? -1 : 1)));
}

function bump(rec: Record<string, number>, key: string): void {
  rec[key] = (rec[key] ?? 0) + 1;
}

function walk(node: ZilNode, visit: (n: ZilNode) => void): void {
  visit(node);
  if ("elements" in node) for (const el of node.elements) walk(el, visit);
  if ("value" in node && typeof node.value === "object") walk(node.value, visit);
}

const PAGE_BREAK_NAMES = new Set(["\f", "^L", "/^L"]);

export function fileStats(program: ProgramNode, src: string): FileStats {
  const topLevelTypes: Record<string, number> = {};
  const topLevelHeads: Record<string, number> = {};
  const deepHeads: Record<string, number> = {};
  let nodes = 0;
  let pageBreaks = 0;

  for (const top of program.body) {
    bump(topLevelTypes, top.type);
    if (top.type === "Form" && top.elements[0]?.type === "Atom") {
      bump(topLevelHeads, top.elements[0].name);
    }
    if (top.type === "Atom" && PAGE_BREAK_NAMES.has(top.name)) pageBreaks++;
    walk(top, (n) => {
      nodes++;
      if (n.type === "Form" && n.elements[0]?.type === "Atom") {
        bump(deepHeads, n.elements[0].name);
      }
    });
  }

  return {
    file: program.source,
    bytes: Buffer.byteLength(src, "utf8"),
    lines: src.split("\n").length,
    nodes,
    topLevelTypes: sortRecord(topLevelTypes),
    topLevelHeads: sortRecord(topLevelHeads),
    deepHeads: sortRecord(deepHeads),
    pageBreaks,
  };
}

export function corpusStats(perFile: FileStats[], generatedBy: string): CorpusStats {
  const totals: CorpusStats["totals"] = {
    bytes: 0,
    lines: 0,
    nodes: 0,
    topLevelHeads: {},
    deepHeads: {},
  };
  for (const f of perFile) {
    totals.bytes += f.bytes;
    totals.lines += f.lines;
    totals.nodes += f.nodes;
    for (const [k, v] of Object.entries(f.topLevelHeads)) {
      totals.topLevelHeads[k] = (totals.topLevelHeads[k] ?? 0) + v;
    }
    for (const [k, v] of Object.entries(f.deepHeads)) {
      totals.deepHeads[k] = (totals.deepHeads[k] ?? 0) + v;
    }
  }
  totals.topLevelHeads = sortRecord(totals.topLevelHeads);
  totals.deepHeads = sortRecord(totals.deepHeads);
  return { generatedBy, files: perFile, totals };
}

/** Human-readable Markdown report. */
export function statsMarkdown(stats: CorpusStats): string {
  const HEADS = [
    "ROOM",
    "OBJECT",
    "ROUTINE",
    "GLOBAL",
    "CONSTANT",
    "SYNTAX",
    "SYNONYM",
    "BUZZ",
    "DEFMAC",
  ] as const;
  const lines: string[] = [];
  lines.push("# Zork I Corpus Statistics");
  lines.push("");
  lines.push(`Generated by \`${stats.generatedBy}\`. Do not edit by hand.`);
  lines.push("");
  lines.push("## Top-level definitions per file");
  lines.push("");
  lines.push(`| File | Lines | AST nodes | ${HEADS.join(" | ")} | Page breaks |`);
  lines.push(`|---|---:|---:|${HEADS.map(() => "---:").join("|")}|---:|`);
  for (const f of stats.files) {
    const cells = HEADS.map((h) => f.topLevelHeads[h] ?? 0);
    lines.push(
      `| ${f.file} | ${f.lines} | ${f.nodes} | ${cells.join(" | ")} | ${f.pageBreaks} |`,
    );
  }
  const totalCells = HEADS.map((h) => stats.totals.topLevelHeads[h] ?? 0);
  lines.push(
    `| **Total** | **${stats.totals.lines}** | **${stats.totals.nodes}** | ${totalCells
      .map((c) => `**${c}**`)
      .join(" | ")} | — |`,
  );
  lines.push("");
  lines.push("## Table constructors (any depth)");
  lines.push("");
  lines.push("| Constructor | Count |");
  lines.push("|---|---:|");
  for (const t of ["TABLE", "LTABLE", "ITABLE", "PLTABLE", "PTABLE"]) {
    if (stats.totals.deepHeads[t]) {
      lines.push(`| ${t} | ${stats.totals.deepHeads[t]} |`);
    }
  }
  lines.push("");
  lines.push("## Full top-level head histogram (corpus)");
  lines.push("");
  lines.push("| Head | Count |");
  lines.push("|---|---:|");
  for (const [head, count] of Object.entries(stats.totals.topLevelHeads)) {
    lines.push(`| ${head} | ${count} |`);
  }
  lines.push("");
  return lines.join("\n");
}
