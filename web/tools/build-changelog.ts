/**
 * Generates the public changelog (DESIGN.md §3.5) from `WORKLOG.md` so the
 * site copy cannot diverge from the internal history the way a hand-kept
 * second changelog would. Writes `changelog.html` (full list) and rewrites
 * the CHANGELOG:START…END block in `index.html` (latest 3).
 *
 * Usage:  tsx tools/build-changelog.ts
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = fileURLToPath(new URL("..", import.meta.url));
const REPO_ROOT = join(WEB_ROOT, "..");
const WORKLOG = join(REPO_ROOT, "WORKLOG.md");

interface Entry {
  version: string;
  date: string;
  summary: string;
}

function parseWorklog(text: string): Entry[] {
  const entries: Entry[] = [];
  const re = /^## v(\S+) — (\d{4}-\d{2}-\d{2}) — (.+)$/gm;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    entries.push({ version: m[1]!, date: m[2]!, summary: m[3]! });
  }
  return entries;
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/`/g, "");
}

function row(e: Entry): string {
  return (
    `            <div class="changelog-row">\n` +
    `              <span class="version">${e.version}</span>\n` +
    `              <span class="date">${e.date}</span>\n` +
    `              <span class="summary">${escapeHtml(e.summary)}</span>\n` +
    `            </div>`
  );
}

const text = readFileSync(WORKLOG, "utf8");
const entries = parseWorklog(text);
if (entries.length === 0) {
  throw new Error(`No "## vX.Y.Z — DATE — summary" entries found in ${WORKLOG}`);
}

// index.html preview: latest 3, file order (top of WORKLOG.md is newest, its own stated rule)
const preview = entries.slice(0, 3).map(row).join("\n");
const indexPath = join(WEB_ROOT, "index.html");
const indexHtml = readFileSync(indexPath, "utf8");
const marker = /<!-- CHANGELOG:START.*?-->[\s\S]*?<!-- CHANGELOG:END -->/;
const replacement =
  `<!-- CHANGELOG:START — generated by tools/build-changelog.ts from WORKLOG.md. Do not hand-edit. -->\n` +
  `${preview}\n` +
  `            <!-- CHANGELOG:END -->`;
if (!marker.test(indexHtml)) {
  throw new Error("index.html is missing the CHANGELOG:START…END marker block");
}
writeFileSync(indexPath, indexHtml.replace(marker, replacement));

// changelog.html: full list
const changelogPath = join(WEB_ROOT, "changelog.html");
const rows = entries.map(row).join("\n");
const template = readFileSync(join(WEB_ROOT, "tools", "changelog.template.html"), "utf8");
writeFileSync(changelogPath, template.replace("<!-- CHANGELOG:ROWS -->", rows));

process.stdout.write(`wrote ${entries.length} entries → index.html (top 3) + changelog.html (all)\n`);
